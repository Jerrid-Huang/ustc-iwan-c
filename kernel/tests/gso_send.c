/*
 * gso_send.c -- **sender side** of the iWAN GSO batch acceptance test (pure libc + _GNU_SOURCE).
 *
 * Purpose: send N **equal-length** encrypted data frames as one UDP super-packet with a single sendmsg(UDP_SEGMENT).
 * The veth features include NETIF_F_GSO_SOFTWARE (including GSO_UDP_L4),
 * so validate_xmit_skb() does not segment early, and the receiver side therefore sees
 * an skb with skb_is_gso() in the netfilter hook and enters iwan_rx_batch() in kernel/iwan_rx.c.
 *
 * Frame construction matches the encap path of kernel/tests/interop_c.c byte for byte (frozen wire format,
 * see src/common/protocol.h):
 *   [outer IPv4 20B][outer UDP 8B]              <- generated by the kernel according to UDP_SEGMENT
 *   [8B frame header: type=0x18, enc, sid(u16 BE), tok(u32 BE)]
 *   [XOR(whole inner IPv4 packet, including inner IP header)]      <- 8-byte session key cycled by byte offset
 * Note: **data frames have no signature** -- the IWAN_CTRL_LEN=24 MD5 signature is only used for control frames
 * (ctrl_hdr/pkt_sig in src/common/protocol.h); this tool sends only data frames, so here
 * there is only the frame header + XOR, exactly the same as interop_c's encap.
 *
 * Why not link src/common directly: this tool deliberately depends only on libc so gso_test.sh does not need
 * libcrypto; consistency with the production implementation is covered by the byte-for-byte comparison in interop_test.sh, and this tool's
 * end-to-end correctness is guaranteed by two things:
 *   - at startup, one XOR round trip + byte-for-byte header self-check on frame 0 (SELFCHECK=ok);
 *   - after kernel decapsulation, the inner UDP checksum is verified against the **plaintext**, and all N packets must be delivered to the socket.
 *
 * Build (this is the exact line gso_test.sh uses):
 *   cc -O2 -std=gnu11 -D_GNU_SOURCE -Wall -Wextra -o gso_send gso_send.c
 *
 * Usage:
 *   gso_send --outer-src IP --outer-dst IP [--sport N] --dport N \
 *            --inner-src IP --inner-dst IP [--inner-sport N] [--inner-dport N] \
 *            [--sid N] [--tok N] [--enc 0|1] [--key HEX16] \
 *            [--count N] [--inner-len N] [--ttl N] [--ip-id N] \
 *            [--dump-frame FILE] [--quiet]
 *
 * stdout is stable KEY=value (parsed by scripts); stderr is human-readable diagnostics;
 * exit codes: 0 success; 1 runtime error (socket/sendmsg/self-check failure); 2 usage error.
 */

